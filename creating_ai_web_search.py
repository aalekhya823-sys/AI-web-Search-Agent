# STEP 2: Import libraries

import os
from getpass import getpass

from smolagents import (
    CodeAgent,
    OpenAIModel,
    DuckDuckGoSearchTool
)


# STEP 3: Get Gemini API key

os.environ["GEMINI_API_KEY"] = getpass(
    "Enter Gemini API Key: "
)


# STEP 4: Connect Gemini 2.5 Flash

model = OpenAIModel(
    model_id="gemini-3.8-flash",
    api_base="https://generativelanguage.googleapis.com/v1beta/openai/",
    api_key=os.environ["GEMINI_API_KEY"]
)


# STEP 5: Create search tool

search_tool = DuckDuckGoSearchTool()


# STEP 6: Create AI agent

agent = CodeAgent(
    tools=[search_tool],
    model=model,
    max_steps=5
)

print("AI Research Agent Created Successfully!")


# STEP 7: Execute task

result = agent.run(
    "Search for five important developments& updates in hugging face"
    "in Artificial Intelligence and summarize them."
)


# STEP 8: Display output

print(result)

